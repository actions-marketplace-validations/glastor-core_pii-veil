use crate::detector::EntityKind;
use crate::strategy::keyed_hash64;
use aho_corasick::AhoCorasick;
use chacha20poly1305::{aead::AeadInPlace, ChaCha20Poly1305, KeyInit, Nonce, Tag};
use pbkdf2::pbkdf2_hmac;
use serde::{Deserialize, Serialize};
use sha2::Sha256;
use std::collections::HashMap;
use std::io::{self, BufRead, Write};

const PBKDF2_ITERATIONS: u32 = 100_000;
const VAULT_V2_AAD: &[u8] = b"pii-veil-vault-v2";

/// A single entry recorded inside a [`Vault`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct VaultEntry {
    pub replacement: String,
    pub original: String,
    pub kind: EntityKind,
}

/// Encrypted vault envelope for safe persistence on disk, S3, or Redis.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EncryptedVaultEnvelope {
    pub version: u8,
    pub nonce_hex: String,
    pub tag_hex: String,
    pub ciphertext_hex: String,
}

/// Reversible mapping store that tracks `original <-> replacement` pairs.
///
/// Use [`Vault::restore`] to convert LLM responses or sanitized logs back to their
/// original PII values in a single linear pass using an Aho-Corasick automaton.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Vault {
    original_to_replacement: HashMap<String, VaultEntry>,
    replacement_to_original: HashMap<String, String>,
    counters: HashMap<String, usize>,
}

impl Vault {
    pub fn new() -> Self {
        Self::default()
    }

    /// Clears all entries and resets entity counters in the vault.
    pub fn clear(&mut self) {
        self.original_to_replacement.clear();
        self.replacement_to_original.clear();
        self.counters.clear();
    }

    /// Returns the existing replacement if `original` was already seen in this vault,
    /// or inserts a new entry generated by `generator(next_index)`.
    pub fn get_or_insert<F>(&mut self, kind: EntityKind, original: &str, generator: F) -> String
    where
        F: FnOnce(usize) -> String,
    {
        if let Some(existing) = self.original_to_replacement.get(original) {
            return existing.replacement.clone();
        }

        let count_entry = self.counters.entry(kind.label().to_string()).or_insert(0);
        *count_entry += 1;
        let idx = *count_entry;

        let replacement = generator(idx);
        let entry = VaultEntry {
            replacement: replacement.clone(),
            original: original.to_string(),
            kind,
        };

        self.original_to_replacement
            .insert(original.to_string(), entry);
        self.replacement_to_original
            .insert(replacement.clone(), original.to_string());

        replacement
    }

    /// Restores all known replacements in `sanitized_text` back to their original values
    /// in a single $O(N)$ pass via `aho-corasick`.
    pub fn restore(&self, sanitized_text: &str) -> String {
        if self.replacement_to_original.is_empty() || sanitized_text.is_empty() {
            return sanitized_text.to_string();
        }

        let mut patterns: Vec<&str> = Vec::with_capacity(self.replacement_to_original.len());
        let mut replacements: Vec<&str> = Vec::with_capacity(self.replacement_to_original.len());

        for (rep, orig) in &self.replacement_to_original {
            patterns.push(rep.as_str());
            replacements.push(orig.as_str());
        }

        match AhoCorasick::new(&patterns) {
            Ok(ac) => ac.replace_all(sanitized_text, &replacements),
            Err(_) => {
                let mut out = sanitized_text.to_string();
                for (rep, orig) in &self.replacement_to_original {
                    out = out.replace(rep, orig);
                }
                out
            }
        }
    }

    /// Streams sanitized lines from `reader` and writes restored original text to `writer`
    /// in $O(1)$ memory per line, compiling the `AhoCorasick` automaton only once.
    pub fn restore_stream<R: BufRead, W: Write>(
        &self,
        mut reader: R,
        mut writer: W,
    ) -> io::Result<usize> {
        let mut patterns: Vec<&str> = Vec::with_capacity(self.replacement_to_original.len());
        let mut replacements: Vec<&str> = Vec::with_capacity(self.replacement_to_original.len());

        for (rep, orig) in &self.replacement_to_original {
            patterns.push(rep.as_str());
            replacements.push(orig.as_str());
        }

        let ac_opt = if patterns.is_empty() {
            None
        } else {
            AhoCorasick::new(&patterns).ok()
        };

        let mut lines = 0usize;
        let mut line_buf = String::with_capacity(4096);
        loop {
            line_buf.clear();
            let n = reader.read_line(&mut line_buf)?;
            if n == 0 {
                break;
            }
            lines += 1;
            if let Some(ref ac) = ac_opt {
                let restored = ac.replace_all(&line_buf, &replacements);
                writer.write_all(restored.as_bytes())?;
            } else {
                writer.write_all(line_buf.as_bytes())?;
            }
        }
        writer.flush()?;
        Ok(lines)
    }

    /// Creates a [`StreamingRestorer`] for real-time LLM token/SSE chunk restoration.
    pub fn streaming_restorer(&self) -> StreamingRestorer {
        StreamingRestorer::new(self.clone())
    }

    /// Number of unique sensitive entities stored in this vault.
    pub fn len(&self) -> usize {
        self.original_to_replacement.len()
    }

    /// Returns `true` if no entities have been recorded.
    pub fn is_empty(&self) -> bool {
        self.original_to_replacement.is_empty()
    }

    /// Returns all entries currently stored in the vault.
    pub fn entries(&self) -> Vec<&VaultEntry> {
        let mut list: Vec<&VaultEntry> = self.original_to_replacement.values().collect();
        list.sort_by(|a, b| a.replacement.cmp(&b.replacement));
        list
    }

    /// Serializes the vault to a JSON string for persistence or cross-service transport.
    pub fn to_json(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string_pretty(self)
    }

    /// Deserializes a vault from a JSON string.
    pub fn from_json(json_str: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json_str)
    }

    /// Encrypts and authenticates the vault with `passphrase` using **PBKDF2-HMAC-SHA256**
    /// (100,000 iterations, random 128-bit salt) and **ChaCha20-Poly1305 AEAD** (random 96-bit nonce),
    /// returning a JSON string containing an [`EncryptedVaultEnvelope`] (`version: 2`).
    pub fn to_encrypted_json(&self, passphrase: &str) -> Result<String, String> {
        let plaintext = self.to_json().map_err(|e| e.to_string())?;

        let mut salt_and_nonce = [0u8; 28];
        getrandom::getrandom(&mut salt_and_nonce)
            .map_err(|e| format!("CSPRNG failure generating vault salt/nonce: {}", e))?;
        let salt = &salt_and_nonce[..16];
        let nonce_bytes = &salt_and_nonce[16..28];

        let mut key = [0u8; 32];
        pbkdf2_hmac::<Sha256>(passphrase.as_bytes(), salt, PBKDF2_ITERATIONS, &mut key);

        let cipher = ChaCha20Poly1305::new_from_slice(&key)
            .map_err(|_| "failed to initialize ChaCha20-Poly1305 cipher".to_string())?;
        let nonce = Nonce::from_slice(nonce_bytes);

        let mut buffer = plaintext.into_bytes();
        let tag = cipher
            .encrypt_in_place_detached(nonce, VAULT_V2_AAD, &mut buffer)
            .map_err(|_| "ChaCha20-Poly1305 encryption failed".to_string())?;

        let envelope = EncryptedVaultEnvelope {
            version: 2,
            nonce_hex: bytes_to_hex(&salt_and_nonce),
            tag_hex: bytes_to_hex(tag.as_slice()),
            ciphertext_hex: bytes_to_hex(&buffer),
        };
        serde_json::to_string_pretty(&envelope).map_err(|e| e.to_string())
    }

    /// Decrypts and verifies a [`Vault`] from an encrypted JSON envelope produced by [`Vault::to_encrypted_json`].
    ///
    /// Supports both `version: 2` (PBKDF2-HMAC-SHA256 + ChaCha20-Poly1305 AEAD) and legacy `version: 1`.
    pub fn from_encrypted_json(encrypted_json: &str, passphrase: &str) -> Result<Self, String> {
        let env: EncryptedVaultEnvelope = serde_json::from_str(encrypted_json)
            .map_err(|e| format!("invalid encrypted vault envelope: {}", e))?;

        match env.version {
            2 => {
                let salt_and_nonce = hex_to_bytes(&env.nonce_hex)?;
                if salt_and_nonce.len() != 28 {
                    return Err("invalid v2 vault salt/nonce length".to_string());
                }
                let salt = &salt_and_nonce[..16];
                let nonce_bytes = &salt_and_nonce[16..28];

                let tag_bytes = hex_to_bytes(&env.tag_hex)?;
                if tag_bytes.len() != 16 {
                    return Err("invalid v2 vault authentication tag length".to_string());
                }

                let mut key = [0u8; 32];
                pbkdf2_hmac::<Sha256>(passphrase.as_bytes(), salt, PBKDF2_ITERATIONS, &mut key);

                let cipher = ChaCha20Poly1305::new_from_slice(&key)
                    .map_err(|_| "failed to initialize ChaCha20-Poly1305 cipher".to_string())?;
                let nonce = Nonce::from_slice(nonce_bytes);
                let tag = Tag::from_slice(&tag_bytes);

                let mut buffer = hex_to_bytes(&env.ciphertext_hex)?;
                cipher
                    .decrypt_in_place_detached(nonce, VAULT_V2_AAD, &mut buffer, tag)
                    .map_err(|_| {
                        "vault authentication failed: wrong passphrase or tampered file".to_string()
                    })?;

                let plaintext = String::from_utf8(buffer)
                    .map_err(|_| "decrypted vault is not valid UTF-8".to_string())?;
                Self::from_json(&plaintext).map_err(|e| e.to_string())
            }
            1 => {
                let expected_tag =
                    compute_auth_tag(passphrase.as_bytes(), &env.nonce_hex, &env.ciphertext_hex);
                if expected_tag != env.tag_hex {
                    return Err(
                        "vault authentication failed: wrong passphrase or tampered file"
                            .to_string(),
                    );
                }

                let ciphertext = hex_to_bytes(&env.ciphertext_hex)?;
                let plaintext_bytes =
                    xor_keystream(passphrase.as_bytes(), &env.nonce_hex, &ciphertext);
                let plaintext = String::from_utf8(plaintext_bytes)
                    .map_err(|_| "decrypted vault is not valid UTF-8".to_string())?;

                Self::from_json(&plaintext).map_err(|e| e.to_string())
            }
            v => Err(format!("unsupported encrypted vault version: {}", v)),
        }
    }
}

fn xor_keystream(passphrase: &[u8], nonce_hex: &str, data: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(data.len());
    for (block_idx, chunk) in data.chunks(8).enumerate() {
        let block_key = keyed_hash64(
            passphrase,
            "VEIL_STREAM_V1",
            &format!("{}:{}", nonce_hex, block_idx),
        )
        .to_le_bytes();
        for (i, &b) in chunk.iter().enumerate() {
            out.push(b ^ block_key[i]);
        }
    }
    out
}

fn compute_auth_tag(passphrase: &[u8], nonce_hex: &str, ciphertext_hex: &str) -> String {
    let t1 = keyed_hash64(
        passphrase,
        "VEIL_MAC_HI",
        &format!("{}:{}", nonce_hex, ciphertext_hex),
    );
    let t2 = keyed_hash64(
        passphrase,
        "VEIL_MAC_LO",
        &format!("{}:{}", ciphertext_hex, nonce_hex),
    );
    format!("{:016x}{:016x}", t1, t2)
}

fn bytes_to_hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for &b in bytes {
        s.push_str(&format!("{:02x}", b));
    }
    s
}

fn hex_to_bytes(hex: &str) -> Result<Vec<u8>, String> {
    if !hex.len().is_multiple_of(2) {
        return Err("invalid hex length".to_string());
    }
    let mut out = Vec::with_capacity(hex.len() / 2);
    let bytes = hex.as_bytes();
    for i in (0..bytes.len()).step_by(2) {
        let sub = std::str::from_utf8(&bytes[i..i + 2]).map_err(|e| e.to_string())?;
        let val = u8::from_str_radix(sub, 16).map_err(|e| e.to_string())?;
        out.push(val);
    }
    Ok(out)
}

/// Stateful chunked restorer for LLM Server-Sent Events (SSE) and token streams.
///
/// Safely buffers incomplete placeholder tokens (e.g. `"[EMA"` followed by `"IL_1]"`)
/// across token boundaries so partial tokens are never emitted un-restored.
/// Compiles the `AhoCorasick` automaton once on creation for zero-recompilation $O(N)$ streaming.
#[derive(Debug, Clone)]
pub struct StreamingRestorer {
    vault: Vault,
    ac: Option<AhoCorasick>,
    replacements: Vec<String>,
    buffer: String,
    max_token_len: usize,
}

impl StreamingRestorer {
    pub fn new(vault: Vault) -> Self {
        let max_token_len = vault
            .replacement_to_original
            .keys()
            .map(|k| k.len())
            .max()
            .unwrap_or(32)
            .max(24);

        let mut patterns: Vec<&str> = Vec::with_capacity(vault.replacement_to_original.len());
        let mut replacements: Vec<String> = Vec::with_capacity(vault.replacement_to_original.len());
        for (rep, orig) in &vault.replacement_to_original {
            patterns.push(rep.as_str());
            replacements.push(orig.clone());
        }
        let ac = if patterns.is_empty() {
            None
        } else {
            AhoCorasick::new(&patterns).ok()
        };

        Self {
            vault,
            ac,
            replacements,
            buffer: String::new(),
            max_token_len,
        }
    }

    #[inline]
    fn restore_slice(&self, text: &str) -> String {
        if text.is_empty() {
            return String::new();
        }
        if let Some(ref ac) = self.ac {
            ac.replace_all(text, &self.replacements)
        } else {
            self.vault.restore(text)
        }
    }

    /// Feeds a new LLM stream chunk and returns the portion that can be safely restored and emitted now.
    pub fn push_chunk(&mut self, chunk: &str) -> String {
        self.buffer.push_str(chunk);

        if self.buffer.is_empty() {
            return String::new();
        }

        // Check if there is an unclosed '[' or '<' near the tail of the buffer.
        // Snap `tail_start` forward to a valid UTF-8 char boundary to prevent panics on multibyte text.
        let mut tail_start = self.buffer.len().saturating_sub(self.max_token_len);
        while tail_start < self.buffer.len() && !self.buffer.is_char_boundary(tail_start) {
            tail_start += 1;
        }
        let tail = &self.buffer[tail_start..];

        if let Some(rel_open_idx) = tail.rfind(['[', '<']) {
            let after_open = &tail[rel_open_idx..];
            // If it hasn't been closed by ']' or '>' yet, hold from that opening bracket
            if !after_open.contains(']') && !after_open.contains('>') {
                let split_pos = tail_start + rel_open_idx;
                if split_pos == 0 {
                    return String::new();
                }
                let ready = self.buffer[..split_pos].to_string();
                self.buffer = self.buffer[split_pos..].to_string();
                return self.restore_slice(&ready);
            }
        }

        let ready = std::mem::take(&mut self.buffer);
        self.restore_slice(&ready)
    }

    /// Flushes and restores any remaining buffered characters at the end of the stream.
    pub fn finish(&mut self) -> String {
        if self.buffer.is_empty() {
            return String::new();
        }
        let remainder = std::mem::take(&mut self.buffer);
        self.restore_slice(&remainder)
    }
}
